/** Bütün dil kodları — döngülerde `LANGUAGES.map` yerine kullanılabilir. */
export const LANGUAGE_CODES = LANGUAGES.map((l) => l.code) as readonly Language[];

/** Sağdan sola yazılan diller. */
export const RTL_LANGUAGES: readonly Language[] = LANGUAGES.filter((l) => l.rtl).map((l) => l.code);

export function isRtl(language: Language): boolean {
  return RTL_LANGUAGES.includes(language);
}

/**
 * Dilin Türkçe adı — form bildirimleri gibi Dilara'nın okuduğu yerlerde
 * kullanılır ("Almanca" gibi), ziyaretçiye gösterilmez.
 */
export function languageName(code: Language): string {
  return LANGUAGES.find((l) => l.code === code)?.nameTr ?? code;
}

