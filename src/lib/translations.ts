export type Language = "tr" | "en" | "fr" | "ru" | "es" | "de" | "ar";

export interface LanguageMeta {
  code: Language;
  /** Dil anahtarındaki kısa kod. */
  label: string;
  flag: string;
  flagIcon: string;
  /** Dilin kendi adı — ziyaretçiye açık listelerde böyle görünür. */
  name: string;
  /** Dilin Türkçe adı — admin paneli Türkçe olduğu için orada bu kullanılır. */
  nameTr: string;
  /** Sağdan sola yazılan diller için `true`; belge yönü buna göre kurulur. */
  rtl?: boolean;
}

